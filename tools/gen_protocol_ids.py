#!/usr/bin/env python3
"""Generate protocol 777 packet-id tables from the vanilla data generator report.

The input is `reports/packets.json`, produced by the version's own data
generator:

    java -DbundlerMainClass=net.minecraft.data.Main -jar server.jar \
        --reports --output generated

`packets.json` is Mojang-generated data and is deliberately not committed; this
script only turns it into protocol constants (packet names and numeric ids,
which are transport metadata) and is re-run by whoever has the report.

    tools/gen_protocol_ids.py --packets /tmp/mcdata/generated/reports/packets.json
    tools/gen_protocol_ids.py --packets ... --horizon-ids /tmp/horizon-check/.../ids.rs

Outputs:
    src/protocol_ids.cpy        state/direction tables + named accessors
    tests/test_protocol_ids.cpy digest test over every table

Exit status is non-zero when the report is internally inconsistent or does not
match the Horizon reference tables.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

STATES = ["handshake", "status", "login", "configuration", "play"]
DIRECTIONS = ["clientbound", "serverbound"]
STATE_CODE = {name: i for i, name in enumerate(STATES)}
DIR_CODE = {name: i for i, name in enumerate(DIRECTIONS)}
STATE_ABBR = {
    "handshake": "hs",
    "status": "st",
    "login": "lg",
    "configuration": "cfg",
    "play": "pl",
}
DIR_ABBR = {"clientbound": "c", "serverbound": "s"}


def load_report(path: Path) -> dict[tuple[str, str], list[str]]:
    raw = json.loads(path.read_text())
    tables: dict[tuple[str, str], list[str]] = {}
    for state in STATES:
        for direction in DIRECTIONS:
            entries = raw.get(state, {}).get(direction)
            if entries is None:
                continue
            names: list[str | None] = [None] * len(entries)
            for full_name, entry in entries.items():
                packet_id = entry["protocol_id"]
                if not isinstance(packet_id, int) or packet_id < 0:
                    raise SystemExit(f"{state}/{direction}: bad id for {full_name}")
                if packet_id >= len(names):
                    raise SystemExit(f"{state}/{direction}: id {packet_id} out of range")
                if names[packet_id] is not None:
                    raise SystemExit(f"{state}/{direction}: duplicate id {packet_id}")
                bare = full_name.split(":", 1)[1] if ":" in full_name else full_name
                names[packet_id] = bare
            if any(n is None for n in names):
                raise SystemExit(f"{state}/{direction}: non-contiguous ids")
            tables[(state, direction)] = names
    return tables


def parse_horizon_ids(path: Path) -> dict[tuple[str, str], list[str]]:
    """Read the NAMES arrays out of Horizon's generated ids.rs."""
    text = path.read_text()
    result: dict[tuple[str, str], list[str]] = {}
    marker = "pub const NAMES: &[&str] = &["
    for match in re.finditer(re.escape(marker), text):
        start = match.end()
        end = text.index("];", start)
        names = re.findall(r'"([^"]*)"', text[start:end])
        before = text[: match.start()]
        state_matches = [
            m for m in re.finditer(r"pub mod (\w+) \{", before) if m.group(1) in STATES
        ]
        direction_matches = list(
            re.finditer(r"pub mod (clientbound|serverbound) \{", before)
        )
        if not state_matches or not direction_matches:
            raise SystemExit(f"cannot attribute NAMES at offset {match.start()}")
        state = state_matches[-1].group(1)
        direction = direction_matches[-1].group(1)
        result[(state, direction)] = names
    return result


def cpyte_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def sanitize(name: str) -> str:
    return re.sub(r"[^0-9a-zA-Z_]", "_", name)


def fnv1a_low31(text: str) -> int:
    h = 14695981039346656037
    for byte in text.encode():
        h ^= byte
        h = (h * 1099511628211) & 0xFFFFFFFFFFFFFFFF
    return h & 0x7FFFFFFF


def table_digest(names: list[str]) -> int:
    stream = "".join(f"{name}={i}\n" for i, name in enumerate(names))
    return fnv1a_low31(stream)


BANNER = """\
# Vortex engine - protocol 777 packet ids (Minecraft 26.3).
#
# GENERATED by tools/gen_protocol_ids.py from the vanilla data generator's
# reports/packets.json; do not edit by hand. The report itself is not part of
# this repository (see docs/PARITY_BOUNDARY.md); these tables are transport
# metadata, not game data.
#
# States: handshake=0 status=1 login=2 configuration=3 play=4.
# Directions: clientbound=0 serverbound=1. Packet names are stored without the
# "minecraft:" namespace.

import stdlib

"""


def emit_module(tables: dict[tuple[str, str], list[str]]) -> str:
    out = [BANNER]
    for state in STATES:
        out.append(f"public def pkt_state_{state}() -> int:\n    return {STATE_CODE[state]}\n\n")
    for direction in DIRECTIONS:
        out.append(f"public def pkt_dir_{direction}() -> int:\n    return {DIR_CODE[direction]}\n\n")

    out.append(
        "public def pkt_empty_names() -> str[]:\n"
        "    str[] names = new str[0]\n"
        "    return names\n\n"
    )
    out.append(
        "public def pkt_empty_ids() -> int64[]:\n"
        "    int64[] ids = new int64[0]\n"
        "    return ids\n\n"
    )

    for state in STATES:
        for direction in DIRECTIONS:
            names = tables.get((state, direction), [])
            key = f"{STATE_CODE[state]}_{DIR_CODE[direction]}"
            out.append(f"def pkt_names_{key}() -> str[]:\n")
            out.append("    str[] names = pkt_empty_names()\n")
            for name in names:
                out.append(f"    append(names, {cpyte_string(name)})\n")
            out.append("    return names\n\n")
            out.append(f"def pkt_ids_{key}() -> int64[]:\n")
            out.append("    int64[] ids = pkt_empty_ids()\n")
            for packet_id in range(len(names)):
                out.append(f"    append(ids, {packet_id})\n")
            out.append("    return ids\n\n")

    out.append(
        "# Names indexed by packet id for one state/direction; empty for an\n"
        "# unknown state or direction.\n"
        "public def pkt_names(state: int, direction: int) -> str[]:\n"
    )
    for state in STATES:
        for direction in DIRECTIONS:
            key = f"{STATE_CODE[state]}_{DIR_CODE[direction]}"
            out.append(
                f"    if state == pkt_state_{state}() and direction == pkt_dir_{direction}():\n"
                f"        return pkt_names_{key}()\n"
            )
    out.append("    return pkt_empty_names()\n\n")

    out.append("public def pkt_table_ids(state: int, direction: int) -> int64[]:\n")
    for state in STATES:
        for direction in DIRECTIONS:
            key = f"{STATE_CODE[state]}_{DIR_CODE[direction]}"
            out.append(
                f"    if state == pkt_state_{state}() and direction == pkt_dir_{direction}():\n"
                f"        return pkt_ids_{key}()\n"
            )
    out.append("    return pkt_empty_ids()\n\n")

    out.append(
        "public def pkt_count(state: int, direction: int) -> int:\n"
        "    return (int)len(pkt_names(state, direction))\n\n"
    )

    out.append(
        "# Numeric id of `name` in one table, or -1. `name` may be bare or\n"
        "# namespace qualified.\n"
        "public def pkt_id(state: int, direction: int, name: str) -> int:\n"
        "    str bare = name\n"
        '    if str_starts(bare, "minecraft:"):\n'
        "        bare = str_slice(bare, 10, text_len(bare))\n"
        "    str[] names = pkt_names(state, direction)\n"
        "    int i = 0\n"
        "    while i < (int)len(names):\n"
        "        if str_equals(names[i], bare):\n"
        "            return i\n"
        "        i += 1\n"
        "    return -1\n\n"
    )

    out.append(
        "# Namespace-qualified name of packet `packet_id`, or \"\" when absent.\n"
        "public def pkt_name(state: int, direction: int, packet_id: int) -> str:\n"
        "    str[] names = pkt_names(state, direction)\n"
        "    if packet_id < 0 or packet_id >= (int)len(names):\n"
        '        return ""\n'
        '    return "minecraft:" + names[packet_id]\n\n'
    )

    out.append(
        "public def pkt_known(state: int, direction: int, packet_id: int) -> bool:\n"
        "    if packet_id < 0:\n"
        "        return false\n"
        "    return packet_id < pkt_count(state, direction)\n\n"
    )

    out.append(
        "# FNV-1a over \"name=id\\n\" for every entry, masked to 31 bits, so a\n"
        "# test can pin the whole table without duplicating it.\n"
        "public def pkt_table_digest(state: int, direction: int) -> uint64:\n"
        "    VStr* sink = vstr_new(4096)\n"
        "    str[] names = pkt_names(state, direction)\n"
        "    int i = 0\n"
        "    while i < (int)len(names):\n"
        "        vstr_put_text(sink, names[i])\n"
        "        vstr_put(sink, code_equals())\n"
        "        vstr_put_text(sink, str(i))\n"
        "        vstr_put(sink, code_newline())\n"
        "        i += 1\n"
        "    uint64 hash = vstr_hash(sink)\n"
        "    vstr_free(sink)\n"
        "    return hash\n\n"
    )

    # Named accessors keep call sites readable and let the compiler see a
    # function instead of a magic number.
    for state in STATES:
        for direction in DIRECTIONS:
            names = tables.get((state, direction), [])
            for packet_id, name in enumerate(names):
                fn = (
                    f"pid_{STATE_ABBR[state]}_{DIR_ABBR[direction]}_"
                    f"{sanitize(name)}"
                )
                out.append(f"public def {fn}() -> int:\n    return {packet_id}\n\n")

    return "".join(out)


def emit_test(tables: dict[tuple[str, str], list[str]]) -> str:
    out = [
        "# Vortex engine - protocol 777 packet table test.\n"
        "#\n"
        "# GENERATED by tools/gen_protocol_ids.py; do not edit by hand.\n"
        "# Build with: ./build.sh --run tests/protocol_ids.txt\n"
        "\n"
        "import stdlib\n"
        "\n",
        "def table_is_dense(state: int, direction: int, fails: int*) -> void:\n"
        "    str[] names = pkt_names(state, direction)\n"
        "    int64[] ids = pkt_table_ids(state, direction)\n"
        "    check(\"names and ids are the same length\", (int)len(names) == (int)len(ids), fails)\n"
        "    int i = 0\n"
        "    int dense = 1\n"
        "    while i < (int)len(ids):\n"
        "        if ids[i] != (int64)i:\n"
        "            dense = 0\n"
        "        i += 1\n"
        "    check(\"ids are dense from zero\", dense == 1, fails)\n"
        "    i = 0\n"
        "    int unique = 1\n"
        "    while i < (int)len(names):\n"
        "        int j = i + 1\n"
        "        while j < (int)len(names):\n"
        "            if str_equals(names[i], names[j]):\n"
        "                unique = 0\n"
        "            j += 1\n"
        "        i += 1\n"
        "    check(\"names are unique\", unique == 1, fails)\n"
        "\n",
        "def main() -> int:\n"
        "    int fails = 0\n",
    ]
    for state in STATES:
        for direction in DIRECTIONS:
            names = tables.get((state, direction), [])
            if not names:
                continue
            digest = table_digest(names)
            label = f"{state}/{direction}"
            if state == "handshake":
                state_expr = "pkt_state_handshake()"
            else:
                state_expr = f"pkt_state_{state}()"
            out.append(
                f"    print(\"protocol_ids: {label} ({len(names)})\")\n"
                f"    table_is_dense({state_expr}, pkt_dir_{direction}(), &fails)\n"
                f"    check_int(\"{label} digest\", "
                f"(int)(pkt_table_digest({state_expr}, pkt_dir_{direction}()) "
                "& (uint64)2147483647), "
                f"{digest}, &fails)\n"
            )
    out.append(
        "\n"
        "    print(\"protocol_ids: anchors\")\n"
        "    check_int(\"handshake intention\", pkt_id(pkt_state_handshake(), pkt_dir_serverbound(), \"intention\"), 0, &fails)\n"
        "    check_int(\"login finished\", pid_lg_c_login_finished(), 2, &fails)\n"
        "    check_int(\"login key\", pid_lg_s_key(), 1, &fails)\n"
        "    check_int(\"configuration registry\", pid_cfg_c_registry_data(), 7, &fails)\n"
        "    check_int(\"configuration finish ack\", pid_cfg_s_finish_configuration(), 3, &fails)\n"
        "    check_int(\"play login\", pid_pl_c_login(), 50, &fails)\n"
        "    check_int(\"play chunk\", pid_pl_c_level_chunk_with_light(), 46, &fails)\n"
        "    check_int(\"play keep alive\", pid_pl_c_keep_alive(), 45, &fails)\n"
        "    check_int(\"play start configuration\", pid_pl_c_start_configuration(), 120, &fails)\n"
        "    check_int(\"play teleport accept\", pid_pl_s_accept_teleportation(), 0, &fails)\n"
        "    check_int(\"play keep alive answer\", pid_pl_s_keep_alive(), 28, &fails)\n"
        "    check_str(\"qualified name\", pkt_name(pkt_state_play(), pkt_dir_clientbound(), 46), \"minecraft:level_chunk_with_light\", &fails)\n"
        "    check_int(\"qualified lookup\", pkt_id(pkt_state_play(), pkt_dir_clientbound(), \"minecraft:level_chunk_with_light\"), 46, &fails)\n"
        "    check(\"unknown id rejected\", pkt_known(pkt_state_play(), pkt_dir_clientbound(), 144) == false, &fails)\n"
        "    check(\"unknown name rejected\", pkt_id(pkt_state_play(), pkt_dir_clientbound(), \"minecraft:nope\") == -1, &fails)\n"
        "\n"
        "    return report(\"protocol_ids\", fails)\n"
    )
    return "".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--packets", required=True, type=Path)
    parser.add_argument("--horizon-ids", type=Path)
    parser.add_argument("--out", type=Path, default=Path("src/protocol_ids.cpy"))
    parser.add_argument("--test-out", type=Path, default=Path("tests/test_protocol_ids.cpy"))
    args = parser.parse_args()

    tables = load_report(args.packets)
    if args.horizon_ids:
        reference = parse_horizon_ids(args.horizon_ids)
        for key, names in tables.items():
            other = reference.get(key)
            if other is None:
                raise SystemExit(f"Horizon ids.rs lacks {key[0]}/{key[1]}")
            if other != names:
                raise SystemExit(f"packet table mismatch for {key[0]}/{key[1]}")
        extra = set(reference) - set(tables)
        if extra:
            raise SystemExit(f"Horizon has tables the report lacks: {sorted(extra)}")

    args.out.write_text(emit_module(tables))
    args.test_out.write_text(emit_test(tables))
    total = sum(len(n) for n in tables.values())
    print(f"wrote {args.out} and {args.test_out}: {total} packets across {len(tables)} tables")
    return 0


if __name__ == "__main__":
    sys.exit(main())
